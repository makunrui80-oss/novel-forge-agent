def detail_outline(book: str, start: int, end: int, text: str, total: int) -> tuple[str, str]:
    json_example = '{"chapters":[{"idx":1,"title":"章节标题","summary":"本章行动、冲突和结果（1-2句）","characters":["人物及变化"],"conflict":"核心冲突","hook":"结尾钩子（无把握则留空）","hook_type":"新信息/新危机/反常举动/未完成动作"}],"batch_notes":{"mainline_progress":"一句话概括主线变化"},"takeaways":[]}'
    user = f"""为后续原创大纲搭建剧情骨架：拆解《{book}》第 {start}-{end} 章（全书共 {total} 章）。

要求：
- 只要剧情骨架，不做文风、对白等细项分析；每章 summary 只写 1-2 句，优先主角行动、冲突、结果和主线变化。
- 章节编号或分段对不上时，按读到的内容拆；可合并、少列或跳过缺失章节，不要为了凑齐条数而停下。
- 原文只有标题时保留标题，并说明缺少正文；不得把标题推测写成剧情事实。
- hook 只有原文确实提供时才写；无把握就留空。不要编造事件、人物或引文。
- batch_notes 只需用一句话概括主线推进；takeaways 可为空数组。

原文如下：
<<<原文开始
{text}
原文结束>>>

只输出精简 JSON，不要 markdown 代码块，不要任何解释。JSON 结构：
{json_example}"""
    return SYSTEM_EDITOR, user


