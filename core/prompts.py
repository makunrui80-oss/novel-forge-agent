NATURAL_SCENE_RULES = """
【段落与对白，不许排得像模板】
整章不能有一种“被排版过”的均匀感：不要连续几段都只有十几字，也不要固定成“四五句对白—几段叙述—又四五句对白”的交替。段落长短跟着人物此刻的注意力、动作停顿和情绪落点走，该长就长，该一句就一句，允许一段只有半句话，也允许一段把动作、心理和对白连着写完。
对白不要连着排成一大块：连着四五句就要用动作、心理、环境或沉默拆开，不要让整页像剧本一样一行一句往下排；但也不要为了拆而把整章切成一样短的小段。长段、短段、对白、叙述要交错，哪一段该长就长。
不要把一场戏写成完整的方案讨论或设定说明：人物可以绕弯、说废话、临时关心别的事，关键信息不必一次交代清楚，允许读者暂时不明白。不要让一个人一次把整套逻辑讲完，长话要被打断、被反问、被动作岔开；偶尔一段长话可以保留，只要它有情绪和现场。
对白不注水：不写寒暄、复述已知信息、互相附和的过场话；每句对白至少承担一个作用——推进、试探、遮掩、发火、示弱、拒绝或转移话题。宁可三句有劲，不要十句正确。普通接话没有戏剧分量，就并入相邻叙述或动作里，不单独占一行。
【对白要有人味和情绪】
让对白像真人当场说话：急起来会顶、会抢话、会改口，心虚会躲、会答非所问，亲近的人说话会省略、会带刺、会突然软下来。
按人物当下情绪自然出现感叹、疑问、反问、设问、打断和没说完的话，不要求每句完整礼貌。需要确认、施压或自我说服时可以用反问和设问，但不要连续套用同一种句式。
一场对话里至少有一次答非所问、抢话、沉默、话题偏移或被打断；不要让每句话都严丝合缝地接上，也不要让每个人都像会接梗、会总结的人。
不是每句对白都要配动作或表情。很多话可以直接说，让读者自己听出语气；动作只在确实改变场面、暴露态度或造成停顿的时候写。
【修辞和用词】
比喻、拟人、通感只在人物当下真会这样感受时用，落笔前能回答“谁在什么处境下这么觉得”；关键的情绪和画面不要干巴巴地陈述，但也不要给每段强行加修辞。
少用专业术语、书面腔和堆砌的形容词：设定、技术、身份信息先转成人物会说的口语再写到纸上，能用日常词就不用生僻词，能让人物自己说就不由旁白解释。
用词具体到地方叫法、零件叫法和手上的物件；允许粗话、俗语和方言词，但不要为了土而土。
少用“仿佛、似乎、像是、一般、般、不由得、缓缓、微微、透着一股”这类书面套词；能用具体动作和名词，就不用形容词和比喻。
允许粗糙、省略、重复和口头语。不要把每句都打磨得完整漂亮，也不要用四字词和排比撑气势。句子可以突然很短，也可以一口气写很长；不要每句都语法完整、逻辑顺滑。
【技术、方案和设定，用大白话说】
技术、方案、路线、配方和规则的解释，合计不超过全章的五分之一；超过就删，只留人物当下用得上的一句大白话。每章至少一半篇幅要写人物正在做的事、说的话和当场反应。
人物谈技术、机械、路线、配方和规矩时，不写型号、参数、原理和专业术语。苏伟强可以顺口说“缸体”“线束”，但不能展开讲原理；其他人物一律说“那个铁疙瘩”“那根线”“西边那个口子”。
不要让人物像做方案汇报：不列步骤、不讲因果链、不一次把“为什么能成”说全。说个大概，说一半，用手比划，用“反正”“你懂的”“就那个东西”带过，剩下的让读者自己拼。
技术信息只保留推动当下冲突的那一点；删掉的部分用情绪、怀疑、讨价还价、生活细节和动作填满，不要把段落切成短句清单。
读者不需要完全听懂方案，只需要听懂人物在争什么、怕什么、信不信对方。要解释就用一句大白话打完，不追加第二句原理。
例如：不写“主电断了就跳备用，二型机有防拆保护”，写“电一断，它自己接上了备用的，这破机器就这毛病”；不写“空车返程可捎带非管制物资，调度模板里有”，写“空车回去也烧油，他们顺手捎点东西，规定里没管”。
【闲笔与不均匀】
允许与主线无关的小动作、环境、身体感觉和短暂走神；不要每段都承担推进剧情的任务，信息密度要有疏有密。有的地方一句带过，有的地方停下来写细，不要平均分配笔墨。
""".strip()

