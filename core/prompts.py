def context_card(constitution_text: str, chapters_text: str, start: int, end: int,
                 plan_text: str = "", previous_deviations: list[dict] | None = None) -> tuple[str, str]:
    previous_text = "（首次检测，无历史偏离报告）"
    if previous_deviations:
        previous_text = "\n".join(
            f"第{d.get('chapter') or '未定位'}章（{d.get('level', '中')}）：{d.get('issue', '')}；证据：{d.get('evidence', '')}；建议：{d.get('suggestion', '')}"
            for d in previous_deviations
        )
    user = f"""下面是刚写完的第 {start}-{end} 章正文。请生成给下一批使用的「承接卡」，并检查是否偏离创作宪法。

【创作宪法】
{constitution_text}

【本批正文】
{chapters_text}

【本批章节计划】
{plan_text or "（未找到章节计划，请依据创作宪法判断）"}

【之前的偏离报告（如果正在重新承接）】
{previous_text}

要求：
- context_card 必须能让没读过前文的人无缝续写：关键事件按顺序、人物位置与状态、关系变化、未回收伏笔、下一批开头要接住的画面。
- character_states 覆盖本批所有出场的重要人物。
- deviations 只报真实存在的偏离（人物崩坏、节奏拖沓、爽点缺失、设定冲突、提前透支剧情）；没有就返回空数组。每条必须填写 chapter（本批中的实际章号）、evidence（正文证据），不能只写“本批”。level 用 轻/中/重。
- 严格按约束的触发条件与频率检查：“每卷至少一次”不能因某一章没有发生就报偏离；人物有弱点不等于每次出场都失误。未同场的人物不必为凑互动而见面。区分硬事实冲突、计划缺项与可选文风建议，文风偏好不报剧情偏离。
- 承接卡只记录正文已发生的事实，纠偏建议不得混写成事实。优先建议在实际偏离章修复；如建议后续补足，只给最小过渡，不强制未来章改主线、补写整段已过事件或扭曲人物来补罚。
- 重新承接时要逐条重新核对旧报告：确认属实的，保留并写清下一批的纠偏动作；不属实的不要照抄；如无法定位，可从本批正文中重新定位。纠偏动作写进 context_card 和 next_hook，使下一批可执行。
- 不要复述原文，要提炼成可执行的信息。

只输出 JSON，不要 markdown 代码块：
{CONTEXT_SCHEMA}"""
    return SYSTEM_EDITOR, user


def de_aigc(text: str, score: float | None, target: float, round_no: int = 0,
            memory: str = "") -> tuple[str, str]:
    # 检测分只作为内部反馈，不把“降到某个分数”直接交给模型，避免模型生成
    # 另一套固定的“反检测腔”。目标是可读、自然、有人物差异的正文。
    rhythm = [
        "优先检查对白是否符合人物目的和关系，不人为添加口头禅或争吵。",
        "优先检查叙述节奏，删除重复解释，不为改变句长而拆碎完整动作。",
        "优先改动作细节：删掉泛泛的情绪词，只留下能证明情绪的具体动作。",
    ][round_no % 3]
    user = f"""请对下面这章小说做一次自然的人工编辑重写。这是第 {round_no + 1} 次编辑，不要围绕检测分数写作，也不要在正文中提到检测、AI 或改写。

【改写原则】
1. 情节、人物、对话信息、章节标题全部保留，不许增删剧情。
2. 修整生硬句式和重复表达，不逐句机械替换同义词。
3. 删掉套话和泛化抒情，准确有用的普通词不必禁用。
4. 把抽象情绪改成具体动作和感官细节（手上的动作、声音、温度、气味）。
5. 对白符合角色知识、关系和目的，必要时才保留停顿、打断或省略。
6. 减少成语堆砌和多余总结，保留推进剧情的叙述。
7. 保留原有伏笔和章末钩子，不升级危机、不新增事件来制造刺激。
8. 字数与原文相差不超过 10%。
9. 不要把每段都写成同样长度，不要让每个人都用完整、礼貌、信息密度相同的句子说话；保留人物各自的口头习惯、犹豫和小失误。
10. 场景细节必须服务于当下动作，避免批量替换同义词；每一处新增细节都要能回答“谁看见/听见/碰到了什么”。
11. 本轮编辑重点：{rhythm}

【剧情边界（必须先读，不得为改文风改变事实）】
{memory}

【原文】
{text}

只输出改写后的章节正文，保留「## 第X章 标题」，不要解释，不要输出检测说明。"""
    return SYSTEM_WRITER, user


